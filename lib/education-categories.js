export function getEducationCategoryPath(categoryOrSlug) {
  const slug = typeof categoryOrSlug === "string" ? categoryOrSlug : categoryOrSlug?.slug;
  return slug ? `/utbildningar/${slug}` : "/utbildningar";
}

export function getEducationCategoryBySlug(value) {
  const raw = Array.isArray(value) ? value[0] : value;
  const text = String(raw || "").trim().toLowerCase();
  if (!text) return null;

  let slug = text;
  try {
    slug = decodeURIComponent(text);
  } catch {}

  return educationCategoryPages.find((category) => category.slug === slug) || null;
}
